"""Compliance frameworks built into Atrium: the CyberFundamentals (CyFun) catalogs of the Centre for Cybersecurity
Belgium, CyFun 2025 and CyFun 2023.

The catalogs (``cyfun2025.json``, ``cyfun2023.json`` next to this file) are generated by
``scripts/build_cyfun_catalog.py`` from the CISO Assistant library copies of the frameworks. They hold requirement ids,
the function / category / subcategory tree, the level tags (``B`` / ``I`` / ``E``, key measures ``BK`` / ``IK`` /
``EK``, management aspects ``BG`` / ``IG`` / ``EG`` in 2025) and short titles taken from the NIST CSF (public domain).
The CCB's requirement text is not shipped: every requirement links to cyfun.eu for it.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import date
from functools import lru_cache
from pathlib import Path
from typing import Any

HERE = Path(__file__).parent
CATALOG_IDS = ("cyfun2025", "cyfun2023")
DEFAULT_ID = "cyfun2025"
LEVELS = ("B", "I", "E")
LEVEL_NAMES = {"B": "Basic", "I": "Important", "E": "Essential"}
TEXT_URL = "https://cyfun.eu"
# CISO Assistant's library URNs: which frameworks a connected instance has loaded (and the CRA, available through it)
LIBRARY_URNS = {
    "cyfun2025": "urn:intuitem:risk:library:ccb-cyfun2025",
    "cyfun2023": "urn:intuitem:risk:library:ccb-cff-2023-03-01",
    "cra": "urn:intuitem:risk:library:cra-resolution-annexes",
}
LIBRARY_NAMES = {"cyfun2025": "CyFun 2025", "cyfun2023": "CyFun 2023", "cra": "Cyber Resilience Act (CRA)"}

# The two maturity dimensions share CyFun 2025's scale names (library scores_definition); the one-line descriptions
# are Atrium's own wording, not the CCB's.
SCALE = (
    {"score": 1, "name": "Initial",
     "implementation": "Done ad hoc or not at all; no standard process.",
     "documentation": "Not documented, or not approved."},
    {"score": 2, "name": "Repeatable",
     "implementation": "Done informally and repeated, but not consistently or completely.",
     "documentation": "Documented and approved, but outdated (more than two years old) or incomplete."},
    {"score": 3, "name": "Defined",
     "implementation": "A formal process is in place and followed, with evidence for most activities.",
     "documentation": "Approved, current documentation that is communicated to the people concerned."},
    {"score": 4, "name": "Managed",
     "implementation": "Followed everywhere with evidence, measured against targets, few exceptions.",
     "documentation": "Reviewed regularly; metrics and targets are documented."},
    {"score": 5, "name": "Optimizing",
     "implementation": "Measured and continually improved; exceptions are rare.",
     "documentation": "Continually improved from measurements and lessons learned."},
)


@dataclass(frozen=True)
class Requirement:
    ref_id: str
    function: str
    category: str
    subcategory: str
    tags: tuple[str, ...]
    title: str

    def level(self) -> str:
        """The lowest level that requires it (levels are cumulative: B is also I and E)."""
        return next(level for level in LEVELS if level in self.tags)

    def in_level(self, level: str) -> bool:
        return level in self.tags

    def key_measure(self, level: str) -> bool:
        return f"{level}K" in self.tags

    def management(self, level: str) -> bool:
        return f"{level}G" in self.tags

    def public(self) -> dict[str, Any]:
        return {"ref_id": self.ref_id, "function": self.function, "category": self.category,
                "subcategory": self.subcategory, "tags": list(self.tags), "title": self.title, "level": self.level(),
                "key_measure": [lvl for lvl in LEVELS if self.key_measure(lvl)],
                "management": [lvl for lvl in LEVELS if self.management(lvl)], "text_url": TEXT_URL}


@dataclass(frozen=True)
class Catalog:
    id: str
    data: dict[str, Any] = field(repr=False)
    requirements: tuple[Requirement, ...] = ()

    @property
    def by_ref(self) -> dict[str, Requirement]:
        return _by_ref(self.id)

    @property
    def name(self) -> str:
        return self.data["name"]

    @property
    def short_name(self) -> str:
        return self.data["short_name"]

    @property
    def management_aspects(self) -> bool:
        return any(level.get("management_aspects") for level in self.data["levels"])

    def conformity(self, level: str) -> dict[str, Any]:
        return self.data["conformity"]["levels"][level]

    def group_target(self, group: str) -> float:
        return float(self.data["conformity"]["group_targets"][group])

    @property
    def na_counts_as(self) -> float:
        return float(self.data["conformity"]["na_counts_as"])

    def titles(self, kind: str) -> dict[str, str]:
        return {item["id"]: item["title"] for item in self.data[kind]}

    def transition(self, today: date | None = None) -> dict[str, Any] | None:
        """The edition's transition window (CyFun 2023: new assessments allowed until 18 April 2027)."""
        window = self.data.get("transition")
        if not window:
            return None
        today = today or date.today()
        return {**window, "open": today <= date.fromisoformat(window["assess_until"])}

    def maps_to(self) -> dict[str, list[dict[str, str]]]:
        """For CyFun 2023: requirement -> the CyFun 2025 requirements it maps to (CISO Assistant's mapping)."""
        out: dict[str, list[dict[str, str]]] = {}
        for src, dst, relationship in (self.data.get("edition_mapping") or {}).get("pairs", []):
            out.setdefault(src, []).append({"ref_id": dst, "relationship": relationship})
        return out


@lru_cache(maxsize=None)
def load(framework_id: str) -> Catalog:
    if framework_id not in CATALOG_IDS:
        raise KeyError(framework_id)
    data = json.loads((HERE / f"{framework_id}.json").read_text(encoding="utf-8"))
    requirements = tuple(Requirement(ref_id=r["ref_id"], function=r["function"], category=r["category"],
                                     subcategory=r["subcategory"], tags=tuple(r["tags"]), title=r["title"])
                         for r in data["requirements"])
    return Catalog(id=framework_id, data=data, requirements=requirements)


@lru_cache(maxsize=None)
def _by_ref(framework_id: str) -> dict[str, Requirement]:
    return {r.ref_id: r for r in load(framework_id).requirements}


def get(framework_id: str) -> Catalog | None:
    try:
        return load(framework_id)
    except KeyError:
        return None


def summary(catalog: Catalog) -> dict[str, Any]:
    data = catalog.data
    return {
        "id": catalog.id, "kind": "builtin", "name": data["name"], "short_name": data["short_name"],
        "edition": data["edition"], "publisher": data["publisher"], "based_on": data["based_on"],
        "text_url": data["text_url"], "notice": data["notice"], "default": catalog.id == DEFAULT_ID,
        "counts": data["counts"], "transition": catalog.transition(),
        "source": {k: data["source"][k] for k in ("library_urn", "framework_urn", "library_name", "version",
                                                    "publication_date", "provider", "packager", "url")},
        "titles_source": data["source"]["titles"]["name"],
        "levels": [{**level, "requirements": data["counts"][level["id"]],
                    "key_measures_count": data["counts"][level["key_measures"]]} for level in data["levels"]],
        "conformity_source": data["conformity"]["source"],
        "conformity_verified_against_library": data["conformity"]["verified_against_library"],
    }


def tree(catalog: Catalog) -> list[dict[str, Any]]:
    """function -> category -> subcategory -> requirements, with titles and tags."""
    subs: dict[str, list[dict[str, Any]]] = {}
    for requirement in catalog.requirements:
        subs.setdefault(requirement.subcategory, []).append(requirement.public())
    cats: dict[str, list[dict[str, Any]]] = {}
    for sub in catalog.data["subcategories"]:
        cats.setdefault(sub["category"], []).append({**sub, "requirements": subs.get(sub["id"], [])})
    funcs: dict[str, list[dict[str, Any]]] = {}
    for cat in catalog.data["categories"]:
        funcs.setdefault(cat["function"], []).append({**cat, "subcategories": cats.get(cat["id"], [])})
    return [{**fn, "categories": funcs.get(fn["id"], [])} for fn in catalog.data["functions"]]


def detail(catalog: Catalog) -> dict[str, Any]:
    data = catalog.data
    return {**summary(catalog), "scale": {"min": 1, "max": 5, "levels": list(SCALE),
                                          "dimensions": ["implementation", "documentation"]},
            "conformity": data["conformity"], "corrections": data.get("corrections", []),
            "own_titles": data.get("own_titles", []), "tree": tree(catalog),
            "maps_to": catalog.maps_to() or None}
