class IdentityProvider(BaseModel):
    tool_id: str
    name: str
    kind: IdpKind
    base_url: str
    configured: bool  # False while base_url is a placeholder
    protocols: list[Protocol]
    issuer: str  # the issuer of the provider (authentik: of Atrium's own application)
    settings: dict[str, str] = {}
    path: str | None = None  # the provider's files on disk (used to find its compose service)

    @property
    def realm(self) -> str:
        return self.settings.get("realm") or DEFAULT_REALM

    @property
    def slug(self) -> str:
        return self.settings.get("slug") or DEFAULT_SLUG

    def client_issuer(self, app_slug: str | None = None) -> str:
        """The issuer a client sees. authentik issues per application ({base}/application/o/{slug}/)."""
        if self.kind == "authentik" and app_slug:
            return f"{self.base_url}/application/o/{app_slug}/"
        return self.issuer

    def discovery_url(self, app_slug: str | None = None) -> str:
        return self.client_issuer(app_slug).rstrip("/") + "/.well-known/openid-configuration"

    def endpoints(self, app_slug: str | None = None) -> dict[str, str | None]:
        """Authorization, token, userinfo and end-session endpoints where the provider's layout is known.
        For a generic provider they are None: read them from the discovery document."""
        b = self.base_url
        if self.kind == "keycloak":
            p = f"{self.issuer}/protocol/openid-connect"
            return {"authorize": f"{p}/auth", "token": f"{p}/token", "userinfo": f"{p}/userinfo", "end_session": f"{p}/logout"}
        if self.kind == "authentik":
            slug = app_slug or self.slug
            return {"authorize": f"{b}/application/o/authorize/", "token": f"{b}/application/o/token/",
                    "userinfo": f"{b}/application/o/userinfo/", "end_session": f"{b}/application/o/{slug}/end-session/"}
        if self.kind == "zitadel":
            return {"authorize": f"{b}/oauth/v2/authorize", "token": f"{b}/oauth/v2/token",
                    "userinfo": f"{b}/oidc/v1/userinfo", "end_session": f"{b}/oidc/v1/end_session"}
        if self.kind == "authelia":
            return {"authorize": f"{b}/api/oidc/authorization", "token": f"{b}/api/oidc/token",
                    "userinfo": f"{b}/api/oidc/userinfo", "end_session": None}
        return {"authorize": None, "token": None, "userinfo": None, "end_session": None}

    def saml_metadata_url(self, app_slug: str | None = None) -> str | None:
        if "saml" not in self.protocols:
            return None
        if self.kind == "keycloak":
            return f"{self.issuer}/protocol/saml/descriptor"
        if self.kind == "authentik":
            return f"{self.base_url}/application/saml/{app_slug or self.slug}/metadata/"
        return None


def is_provider(tool: Tool) -> bool:
    m = tool.manifest
    return bool(m and ({"auth.oidc", "auth.saml"} & set(m.provides)))


def provider_kind(tool: Tool) -> IdpKind:
    m = tool.manifest
    text = " ".join([tool.id, tool.name, tool.source, m.name if m else "", *(m.stack if m else [])]).lower()
    return next((k for k in KINDS if k in text), "generic")


def _base_url(tool: Tool, settings: dict[str, str]) -> str | None:
    m = tool.manifest
    url = settings.get("base_url") or (m.ui.url if m else None) or (m.api.base_url if m else None)
    if not url and m and m.launch.port:
        url = f"http://localhost:{m.launch.port}"
    return url.rstrip("/") if url else None


def make_provider(tool: Tool, settings: dict[str, str] | None = None) -> IdentityProvider:
    assert tool.manifest is not None
    kind = provider_kind(tool)
    settings = {k: v for k, v in (settings or {}).items() if k in SETTING_KEYS.get(kind, ("base_url",)) and v}
    base = _base_url(tool, settings)
    protocols: list[Protocol] = [p for p in ("oidc", "saml") if f"auth.{p}" in tool.manifest.provides]  # type: ignore[misc]
    provider = IdentityProvider(tool_id=tool.id, name=tool.name, kind=kind, base_url=base or PLACEHOLDER_BASE,
                                configured=base is not None, protocols=protocols, issuer="", settings=settings,
                                path=tool.path)
    if kind == "keycloak":
        provider.issuer = f"{provider.base_url}/realms/{provider.realm}"
    elif kind == "authentik":
        provider.issuer = f"{provider.base_url}/application/o/{provider.slug}/"
    else:
        provider.issuer = provider.base_url
    return provider


def list_providers(tools: list[Tool], settings: dict[str, dict[str, str]] | None = None) -> list[IdentityProvider]:
    settings = settings or {}
    return [make_provider(t, settings.get(t.id)) for t in tools if is_provider(t)]


