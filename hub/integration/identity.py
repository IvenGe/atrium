"""The suite's identity providers, which one each tool signs in through, and the clients registered at them.

A tool is an identity provider when its manifest provides ``auth.oidc`` or ``auth.saml`` (Keycloak, Authentik,
Zitadel, Authelia, or any tool that says so). Hub preferences hold the per-provider settings (Keycloak realm,
Authentik application slug, public URL), the suite default (``identity_provider``) and per-tool choices.
The provider for a tool is chosen in this order: the person's choice for that tool > the provider its manifest
names (``auth.provider``) > the suite default > the only provider in the suite > none (someone has to choose).

Client secrets are generated by the hub once per tool and provider, kept in ``workspace/secrets`` and written only
into files in the hub's workspace. Patches, diffs, API answers, bus messages and the activity log carry the
``CLIENT_SECRET`` placeholder instead.
"""

