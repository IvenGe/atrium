def _new_secret(name: str) -> str:
    if name == "cookie-secret":  # oauth2-proxy wants 16, 24 or 32 bytes, base64
        return base64.urlsafe_b64encode(os.urandom(32)).decode()
    return secrets.token_urlsafe(32)


def _secret_path(workspace: Path, owner: str, provider: str, name: str) -> Path:
    if not (SAFE_ID.match(owner) and SAFE_ID.match(provider)):
        raise ValueError("Unsafe identifier for a secret")
    return workspace / "secrets" / "sso" / f"{owner}--{provider}--{name}"


def secret(workspace: Path, owner: str, provider: str, name: str = "client-secret") -> str:
    """The secret for `owner` (a tool id, or "atrium") at `provider`, generated on first use."""
    path = _secret_path(workspace, owner, provider, name)
    if path.is_file():
        value = path.read_text(encoding="utf-8").strip()
        if value:
            return value
    path.parent.mkdir(parents=True, exist_ok=True)
    value = _new_secret(name)
    path.write_text(value, encoding="utf-8")
    private_file(path)
    return value


def existing_secrets(workspace: Path, owner: str, provider: str) -> list[str]:
    out = []
    for name in SECRET_TOKENS.values():
        path = _secret_path(workspace, owner, provider, name)
        if path.is_file() and path.read_text(encoding="utf-8").strip():
            out.append(path.read_text(encoding="utf-8").strip())
    return out


def fill_secrets(workspace: Path, owner: str, provider: str, changes: list[FileChange]) -> list[FileChange]:
    """Adapter files with the secret placeholders replaced by the real values."""
    out = []
    for change in changes:
        content = change.content
        for token, name in SECRET_TOKENS.items():
            if token in content:
                content = content.replace(token, secret(workspace, owner, provider, name))
        out.append(FileChange(path=change.path, content=content))
    return out


def has_secret(change: FileChange) -> bool:
    return any(token in change.content for token in SECRET_TOKENS)


def private_file(path: Path) -> None:
    try:
        path.chmod(0o600)
    except OSError:  # best effort (Windows ACLs are not mode bits)
        pass


