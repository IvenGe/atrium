def overview(hub: "Hub") -> dict[str, Any]:
    """Providers, the suite default, whether someone has to choose, and every tool's single sign-on status."""
    prefs = load_prefs(hub)
    tools = hub.tools()
    providers = list_providers(tools, prefs.settings)
    ids = {p.tool_id for p in providers}
    default = prefs.default if prefs.default in ids else None
    pending_approvals = {a.payload.get("patch_id"): a.id for a in hub.approvals.list("pending") if a.kind == "patch"}
    rows = []
    for tool in tools:
        m = tool.manifest
        if m is None or tool.id in ids:
            continue
        selection = select(tool, providers, prefs)
        check = next((c for c in (tool.report.checks if tool.report else []) if c.id == "sso"), None)
        patches = sorted((p for p in hub.patches(tool.id) if p.strategy in SSO_STRATEGIES), key=lambda p: -p.created_at)
        pending = next((p for p in patches if p.status == "proposed"), None)
        applied = next((p for p in patches if p.status == "applied" and p.sso), None)
        connected = m.auth.provider in ids and m.auth.sso in ("oidc", "saml", "oauth2")
        if selection.provider and connected and m.auth.provider == selection.provider.tool_id:
            status = "connected"
        elif pending:
            status = "pending"
        elif not providers:
            status = "no_provider"
        elif selection.reason == "needs_choice":
            status = "needs_choice"
        else:
            status = "not_connected"
        rows.append({
            "tool_id": tool.id, "name": tool.name, "kind": m.kind, "sso": m.auth.sso, "status": status,
            "connected_to": m.auth.provider if connected else None,
            "selected": selection.provider.tool_id if selection.provider else None, "reason": selection.reason,
            "choice": prefs.choices.get(tool.id), "strategy": check.fix if check else None,
            "check": check.status if check else None, "detail": check.detail if check else "",
            "pending": {"patch_id": pending.id, "approval_id": pending_approvals.get(pending.id), "strategy": pending.strategy,
                        "provider": pending.sso.provider if pending.sso else None, "title": pending.title} if pending else None,
            "applied": {"patch_id": applied.id, "provider": applied.sso.provider if applied.sso else None,
                        "can_register": bool(applied.sso and applied.sso.register_command)} if applied else None,
        })
    return {
        "providers": [{**p.model_dump(mode="json", exclude={"path"}), "label": KIND_LABEL[p.kind],
                       "is_default": p.tool_id == default, "setting_keys": list(SETTING_KEYS.get(p.kind, ("base_url",))),
                       "discovery_url": p.discovery_url(p.slug if p.kind == "authentik" else None),
                       "saml_metadata_url": p.saml_metadata_url(),
                       "connected": sum(1 for r in rows if r["connected_to"] == p.tool_id),
                       "atrium_redirect_uri": f"{hub.settings.public_url}/api/auth/oidc/callback"} for p in providers],
        "default": default,
        "needs_choice": len(providers) > 1 and default is None,
        "tools": rows,
    }


