from ..models import FileChange, Tool

if TYPE_CHECKING:
    from ..core import Hub

IdpKind = Literal["keycloak", "authentik", "zitadel", "authelia", "generic"]
Protocol = Literal["oidc", "saml"]
KINDS: tuple[IdpKind, ...] = ("keycloak", "authentik", "zitadel", "authelia")
KIND_LABEL = {"keycloak": "Keycloak", "authentik": "authentik", "zitadel": "Zitadel", "authelia": "Authelia",
              "generic": "OpenID Connect provider"}
SETTING_KEYS: dict[str, tuple[str, ...]] = {"keycloak": ("realm", "base_url"), "authentik": ("slug", "base_url")}
DEFAULT_REALM = "hub"
DEFAULT_SLUG = "atrium"  # authentik application of Atrium's own sign-in
PREF_DEFAULT, PREF_SETTINGS, PREF_CHOICES = "identity_provider", "idp_settings", "sso_choices"
PLACEHOLDER_BASE = "https://idp.example.com"  # until the provider's URL is known
SCOPES = "openid profile email"
ATRIUM_GROUPS = ("atrium-admins", "atrium-operators")
SSO_STRATEGIES = ("sso_connect", "sso_code", "sso_proxy")  # patch strategies that close a single sign-on gap
COMPOSE_FILES = ("docker-compose.yml", "docker-compose.yaml", "compose.yml", "compose.yaml")

# Placeholders the hub replaces with generated secrets when it writes adapter files (never anywhere else).
CLIENT_SECRET = "<generated-client-secret>"
COOKIE_SECRET = "<generated-cookie-secret>"
SECRET_TOKENS = {CLIENT_SECRET: "client-secret", COOKIE_SECRET: "cookie-secret"}
SAFE_ID = re.compile(r"^[a-z0-9][a-z0-9._-]{0,63}$")
REALM_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")
SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9_-]{0,49}$")


