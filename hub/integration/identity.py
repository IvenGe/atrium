@dataclass
class IdentityPrefs:
    default: str | None = None
    choices: dict[str, str] = field(default_factory=dict)
    settings: dict[str, dict[str, str]] = field(default_factory=dict)
    llm: bool = False  # Claude is available (decides between a code patch and the proxy)


def load_prefs(hub: "Hub") -> IdentityPrefs:
    prefs = hub.prefs
    return IdentityPrefs(default=prefs.get(PREF_DEFAULT), choices=dict(prefs.get(PREF_CHOICES) or {}),
                         settings={k: dict(v) for k, v in (prefs.get(PREF_SETTINGS) or {}).items()},
                         llm=hub.llm.available)


@dataclass
class Selection:
    provider: IdentityProvider | None
    reason: Literal["choice", "manifest", "default", "only", "none", "needs_choice"]
    candidates: list[IdentityProvider]


def select(tool: Tool, providers: list[IdentityProvider], prefs: IdentityPrefs | None = None) -> Selection:
    """Which identity provider `tool` should sign in through."""
    prefs = prefs or IdentityPrefs()
    candidates = [p for p in providers if p.tool_id != tool.id]
    by_id = {p.tool_id: p for p in candidates}
    if not candidates:
        return Selection(None, "none", candidates)
    declared = tool.manifest.auth.provider if tool.manifest else None
    for reason, wanted in (("choice", prefs.choices.get(tool.id)), ("manifest", declared), ("default", prefs.default)):
        if wanted in by_id:
            return Selection(by_id[wanted], reason, candidates)  # type: ignore[arg-type]
    if len(candidates) == 1:
        return Selection(candidates[0], "only", candidates)
    return Selection(None, "needs_choice", candidates)


def set_choice(hub: "Hub", tool_id: str, provider_id: str | None) -> None:
    choices = dict(hub.prefs.get(PREF_CHOICES) or {})
    if provider_id:
        choices[tool_id] = provider_id
    else:
        choices.pop(tool_id, None)
    hub.put_pref(PREF_CHOICES, choices)


def set_default(hub: "Hub", provider_id: str | None) -> None:
    hub.put_pref(PREF_DEFAULT, provider_id)


def set_settings(hub: "Hub", provider_id: str, values: dict[str, str | None]) -> dict[str, str]:
    """Merge settings for one provider; an empty value removes that setting."""
    all_settings = {k: dict(v) for k, v in (hub.prefs.get(PREF_SETTINGS) or {}).items()}
    current = all_settings.get(provider_id, {})
    for key, value in values.items():
        if value:
            current[key] = value
        else:
            current.pop(key, None)
    all_settings[provider_id] = current
    hub.put_pref(PREF_SETTINGS, all_settings)
    return current


def validate_setting(key: str, value: str) -> str:
    value = value.strip()
    if key == "realm" and not REALM_RE.match(value):
        raise ValueError("A Keycloak realm name is 1-64 letters, digits, dots, dashes or underscores.")
    if key == "slug" and not SLUG_RE.match(value):
        raise ValueError("An authentik application slug is 1-50 lowercase letters, digits, dashes or underscores.")
    if key == "base_url":
        if not re.match(r"^https?://[^\s/]+(/[^\s]*)?$", value):
            raise ValueError("The provider URL must start with http:// or https://")
        value = value.rstrip("/")
    return value


def forget_tool(hub: "Hub", tool_id: str) -> None:
    """Drop a removed tool from the identity preferences (as a provider and as a tool)."""
    prefs = hub.prefs
    if prefs.get(PREF_DEFAULT) == tool_id:
        hub.put_pref(PREF_DEFAULT, None)
    choices = {k: v for k, v in (prefs.get(PREF_CHOICES) or {}).items() if tool_id not in (k, v)}
    if choices != (prefs.get(PREF_CHOICES) or {}):
        hub.put_pref(PREF_CHOICES, choices)
    if tool_id in (prefs.get(PREF_SETTINGS) or {}):
        hub.put_pref(PREF_SETTINGS, {k: v for k, v in prefs[PREF_SETTINGS].items() if k != tool_id})


