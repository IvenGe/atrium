class AtriumClient(BaseModel):
    """What Atrium needs to sign people in through `provider` (HUB_OIDC_* settings). The secret stays a SecretStr:
    model_dump masks it, so it never reaches an API answer by accident."""

    provider: str
    provider_name: str
    issuer: str
    client_id: str = "atrium"
    client_secret: SecretStr
    redirect_uri: str
    scopes: str = SCOPES
    role_claim: str = "groups"
    admin_values: list[str] = [ATRIUM_GROUPS[0]]
    operator_values: list[str] = [ATRIUM_GROUPS[1]]
    location: str  # folder with the generated files
    secret_file: str  # env file with the secret (HUB_OIDC_CLIENT_SECRET)
    register_command: str | None = None
    steps: list[str] = []

    def public(self) -> dict[str, Any]:
        return {**self.model_dump(mode="json", exclude={"client_secret"}), "env": self.env()}

    def env(self, reveal: bool = False) -> str:
        value = self.client_secret.get_secret_value() if reveal else f"<see {Path(self.secret_file).name}>"
        return "\n".join([f"HUB_OIDC_ISSUER={self.issuer}", f"HUB_OIDC_CLIENT_ID={self.client_id}",
                          f"HUB_OIDC_CLIENT_SECRET={value}", f"HUB_OIDC_SCOPES={self.scopes}",
                          f"HUB_OIDC_ROLE_CLAIM={self.role_claim}", f"HUB_OIDC_ADMIN_VALUES={','.join(self.admin_values)}",
                          f"HUB_OIDC_OPERATOR_VALUES={','.join(self.operator_values)}"]) + "\n"


def write_files(root: Path, files: list[FileChange], private: set[str]) -> None:
    from .patches import write_changes  # late import: patches imports this module

    write_changes(root, files)
    for path in private:
        private_file(root / path)


def atrium_client(hub: "Hub", provider_id: str) -> AtriumClient:
    """Generate (or refresh) the client Atrium itself signs in with at `provider_id`, with its registration files.

    The secret is generated once and kept in the workspace; the files land in workspace/identity/atrium/<provider>.
    A later Sign-in & SSO settings screen consumes the returned values (client_secret.get_secret_value())."""
    prefs = load_prefs(hub)
    provider = next((p for p in list_providers(hub.tools(), prefs.settings) if p.tool_id == provider_id), None)
    if provider is None:
        raise KeyError(provider_id)
    if "oidc" not in provider.protocols:
        raise ValueError(f"{provider.name} does not offer OpenID Connect, which Atrium's sign-in uses.")
    public_url = hub.settings.public_url
    spec = ClientSpec(client_id="atrium", name="Atrium", redirect_uris=[f"{public_url}/api/auth/oidc/callback"],
                      root_url=public_url, app_slug=provider.slug, groups=list(ATRIUM_GROUPS))
    reg = registration(provider, spec, folder="")
    workspace = hub.settings.workspace
    root = workspace / "identity" / "atrium" / provider.tool_id
    value = secret(workspace, "atrium", provider.tool_id)
    client = AtriumClient(provider=provider.tool_id, provider_name=provider.name, issuer=provider.client_issuer(provider.slug),
                          client_secret=SecretStr(value), redirect_uri=spec.redirect_uris[0], location=str(root),
                          secret_file=str(root / "atrium-oidc.env"))
    env_file = FileChange(path="atrium-oidc.env", content=f"# Atrium sign-in through {provider.name}: put these lines in "
                          "Atrium's .env and restart it. Keep this file private.\n" + client.env(reveal=True))
    private = {f.path for f in reg.files if has_secret(f)} | {env_file.path}
    write_files(root, fill_secrets(workspace, "atrium", provider.tool_id, reg.files) + [env_file], private)
    if reg.script:
        client.register_command = f'bash "{(root / reg.script).as_posix()}"'
    client.steps = reg.steps + [
        f"Copy the HUB_OIDC_* lines from {env_file.path} into Atrium's .env and restart Atrium.",
        f"Put people in the groups {ATRIUM_GROUPS[0]} (admin) or {ATRIUM_GROUPS[1]} (operator) at {provider.name}; "
        "everyone else signs in as viewer.",
    ]
    return client
