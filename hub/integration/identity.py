class ClientSpec(BaseModel):
    """A client (relying party / service provider) to register at an identity provider."""

    client_id: str  # OIDC client id, or the SAML service provider's entity id
    name: str
    protocol: Protocol = "oidc"
    redirect_uris: list[str] = []
    root_url: str | None = None
    public: bool = False  # OIDC public client with PKCE, no secret (e.g. Zammad)
    app_slug: str | None = None  # authentik application slug (defaults to the client id)
    groups: list[str] = []  # groups to create at the provider (Atrium's role groups)
    acs_url: str | None = None  # SAML assertion consumer service
    slo_url: str | None = None
    name_id: str = "username"


@dataclass
class Registration:
    files: list[FileChange]  # relative to the folder they are written to
    steps: list[str]
    script: str | None = None  # relative path of the script that registers the client


def sh(value: str) -> str:
    return shlex.quote(value)


def yq(value: Any) -> str:
    """A YAML scalar (JSON strings are valid YAML)."""
    return json.dumps(value)


def compose_target(provider: IdentityProvider) -> tuple[str, str] | None:
    """(compose project folder, service) when the provider runs from a compose file the hub can see."""
    if not provider.path:
        return None
    root = Path(provider.path)
    for name in COMPOSE_FILES:
        path = root / name
        if not path.is_file():
            continue
        try:
            data = yaml.safe_load(path.read_text(encoding="utf-8", errors="replace")) or {}
        except yaml.YAMLError:
            return None
        services = data.get("services") if isinstance(data, dict) else None
        if not isinstance(services, dict) or not services:
            return None
        names = [str(n) for n in services]
        if provider.kind == "authentik" and "worker" in names:  # the worker applies blueprints
            return root.as_posix(), "worker"
        for svc, spec in services.items():
            image = str(spec.get("image", "")) if isinstance(spec, dict) else ""
            if provider.kind in str(svc).lower() or provider.kind in image.lower():
                return root.as_posix(), str(svc)
        return root.as_posix(), names[0]
    return None


def keycloak_client(c: ClientSpec) -> dict[str, Any]:
    """Keycloak ClientRepresentation (admin REST API / kcadm.sh -f)."""
    if c.protocol == "saml":
        # Attribute names as Keycloak exports them for SAML clients (assumption: Keycloak 17+).
        attributes = {
            "saml_assertion_consumer_url_post": c.acs_url or "",
            "saml.authnstatement": "true",
            "saml.server.signature": "true",
            "saml.client.signature": "false",
            "saml.signature.algorithm": "RSA_SHA256",
            "saml_name_id_format": c.name_id,
            "saml_force_name_id_format": "true",
        }
        if c.slo_url:
            attributes["saml_single_logout_service_url_redirect"] = c.slo_url
        rep: dict[str, Any] = {"clientId": c.client_id, "name": c.name, "protocol": "saml", "enabled": True,
                               "frontchannelLogout": True, "attributes": attributes,
                               "redirectUris": c.redirect_uris or ([f"{c.root_url}/*"] if c.root_url else [])}
        if c.root_url:
            rep["rootUrl"] = rep["baseUrl"] = c.root_url
        return rep
    rep = {"clientId": c.client_id, "name": c.name, "protocol": "openid-connect", "enabled": True,
           "publicClient": c.public, "standardFlowEnabled": True, "implicitFlowEnabled": False,
           "directAccessGrantsEnabled": False, "serviceAccountsEnabled": False,
           "redirectUris": c.redirect_uris, "webOrigins": ["+"],
           "attributes": {"post.logout.redirect.uris": "+"}}
    if c.root_url:
        rep["rootUrl"] = rep["baseUrl"] = c.root_url
    if c.public:
        rep["attributes"]["pkce.code.challenge.method"] = "S256"
    else:
        rep["clientAuthenticatorType"] = "client-secret"
        rep["secret"] = CLIENT_SECRET
    # A "groups" claim (group names, not paths) in the ID token, access token and userinfo: Atrium's role mapping
    # and the role mappings the hub generates for tools (e.g. Grafana) read it.
    rep["protocolMappers"] = [{
        "name": "groups", "protocol": "openid-connect", "protocolMapper": "oidc-group-membership-mapper",
        "consentRequired": False,
        "config": {"full.path": "false", "id.token.claim": "true", "access.token.claim": "true",
                   "userinfo.token.claim": "true", "claim.name": "groups"},
    }]
    return rep


def _keycloak_scripts(provider: IdentityProvider, c: ClientSpec) -> tuple[str, str | None]:
    groups = " ".join(sh(g) for g in c.groups)
    group_lines = (f'for g in {groups}; do kc create groups -r "$REALM" -s name="$g" >/dev/null 2>&1 || true; done\n'
                   if c.groups else "")
    body = textwrap.dedent("""\
        kc get "realms/$REALM" >/dev/null 2>&1 || kc create realms -s realm="$REALM" -s enabled=true
        ID="$(kc get clients -r "$REALM" -q clientId="$CLIENT_ID" --fields id --format csv --noquotes | head -n 1 | tr -d '\\r')"
        if [ -n "$ID" ]; then
          kc update "clients/$ID" -r "$REALM" -f - < "$HERE/keycloak-client.json"
          echo "Updated client $CLIENT_ID in realm $REALM"
        else
          kc create clients -r "$REALM" -f - < "$HERE/keycloak-client.json"
          echo "Created client $CLIENT_ID in realm $REALM"
        fi
        """) + group_lines
    head = textwrap.dedent(f"""\
        # Generated by the Atrium Patch Agent. Safe to run again: an existing client is updated.
        # Written for kcadm.sh of Keycloak 17+ (no /auth path). The client secret is in keycloak-client.json;
        # this script never prints it.
        set -euo pipefail
        HERE="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
        REALM="${{KEYCLOAK_REALM:-{provider.realm}}}"
        CLIENT_ID={sh(c.client_id)}
        """)
    host = ("#!/usr/bin/env bash\n"
            f"# Registers {c.name} ({c.protocol.upper()} client {c.client_id}) in Keycloak realm {provider.realm} at {provider.base_url}\n"
            "# with kcadm.sh on this machine. It needs a Keycloak administrator: set KEYCLOAK_ADMIN_USER and\n"
            "# KEYCLOAK_ADMIN_PASSWORD (environment, or a .env file next to this script). The hub never stores them.\n"
            + head + textwrap.dedent(f"""\
        if [ -f "$HERE/.env" ]; then set -a; . "$HERE/.env"; set +a; fi
        KCADM="${{KCADM:-kcadm.sh}}"
        SERVER="${{KEYCLOAK_URL:-{provider.base_url}}}"
        : "${{KEYCLOAK_ADMIN_USER:?Set KEYCLOAK_ADMIN_USER and KEYCLOAK_ADMIN_PASSWORD to a Keycloak administrator}}"
        : "${{KEYCLOAK_ADMIN_PASSWORD:?Set KEYCLOAK_ADMIN_PASSWORD}}"
        CONFIG="$(mktemp)"
        trap 'rm -f "$CONFIG"' EXIT
        kc() {{ local cmd="$1"; shift; "$KCADM" "$cmd" --config "$CONFIG" "$@"; }}
        "$KCADM" config credentials --config "$CONFIG" --server "$SERVER" --realm master \\
          --user "$KEYCLOAK_ADMIN_USER" --password "$KEYCLOAK_ADMIN_PASSWORD" >/dev/null
        """) + body)
    target = compose_target(provider)
    if target is None:
        return host, None
    compose_dir, service = target
    compose = ("#!/usr/bin/env bash\n"
               f"# Registers {c.name} ({c.protocol.upper()} client {c.client_id}) in Keycloak realm {provider.realm} by running\n"
               f"# kcadm.sh inside the {service} container of {provider.name} (docker compose exec), signed in with the\n"
               "# administrator the container was started with (KC_BOOTSTRAP_ADMIN_* or KEYCLOAK_ADMIN*).\n"
               + head + textwrap.dedent(f"""\
        export MSYS_NO_PATHCONV=1  # Git Bash on Windows: pass container paths through unchanged
        COMPOSE_DIR="${{KEYCLOAK_COMPOSE_DIR:-{compose_dir}}}"
        SERVICE="${{KEYCLOAK_SERVICE:-{service}}}"
        KCADM=/opt/keycloak/bin/kcadm.sh
        CONFIG=/tmp/kcadm-atrium.config
        dc() {{ (cd "$COMPOSE_DIR" && docker compose exec -T "$@"); }}
        kc() {{ local cmd="$1"; shift; dc "$SERVICE" "$KCADM" "$cmd" --config "$CONFIG" "$@"; }}
        dc -e KC_URL="${{KEYCLOAK_INTERNAL_URL:-http://localhost:8080}}" "$SERVICE" bash -c \\
          'exec /opt/keycloak/bin/kcadm.sh config credentials --config /tmp/kcadm-atrium.config --server "$KC_URL" --realm master --user "${{KC_BOOTSTRAP_ADMIN_USERNAME:-$KEYCLOAK_ADMIN}}" --password "${{KC_BOOTSTRAP_ADMIN_PASSWORD:-$KEYCLOAK_ADMIN_PASSWORD}}"' >/dev/null
        """) + body)
    return host, compose


def authentik_blueprint(provider: IdentityProvider, c: ClientSpec) -> str:
    """An authentik blueprint (YAML with authentik's !Find / !KeyOf tags) for the provider and application.

    Assumes authentik 2024.10+ (providers need an invalidation flow) and the default flows, scope mappings and
    self-signed certificate an authentik installation creates."""
    slug = c.app_slug or c.client_id
    cert = '!Find [authentik_crypto.certificatekeypair, [name, "authentik Self-signed Certificate"]]'
    lines = [f"# authentik blueprint generated by the Atrium Patch Agent: {c.name} signs in through {provider.name}.",
             "# Apply it with `ak apply_blueprint`, or put it in the blueprints folder authentik watches.",
             "version: 1", "metadata:", f"  name: {yq('atrium-' + slug)}", "entries:"]
    model = "authentik_providers_saml.samlprovider" if c.protocol == "saml" else "authentik_providers_oauth2.oauth2provider"
    lines += [f"  - model: {model}", "    id: provider", "    identifiers:", f"      name: {yq(slug)}", "    attrs:",
              "      authorization_flow: !Find [authentik_flows.flow, [slug, default-provider-authorization-implicit-consent]]",
              "      invalidation_flow: !Find [authentik_flows.flow, [slug, default-provider-invalidation-flow]]"]
    if c.protocol == "saml":
        lines += [f"      acs_url: {yq(c.acs_url or '')}", f"      audience: {yq(c.client_id)}", "      sp_binding: post",
                  f"      signing_kp: {cert}"]
    else:
        lines += [f"      client_type: {'public' if c.public else 'confidential'}", f"      client_id: {yq(c.client_id)}"]
        if not c.public:
            lines.append(f"      client_secret: {yq(CLIENT_SECRET)}")
        lines.append("      redirect_uris:")
        for uri in c.redirect_uris:
            if uri.endswith("/*"):  # a prefix: authentik matches it as a regular expression
                lines += ["        - matching_mode: regex", f"          url: {yq('^' + re.escape(uri[:-2]) + '/.*$')}"]
            else:
                lines += ["        - matching_mode: strict", f"          url: {yq(uri)}"]
        lines += [f"      signing_key: {cert}", "      property_mappings:",
                  *(f"        - !Find [authentik_providers_oauth2.scopemapping, [scope_name, {s}]]" for s in ("openid", "email", "profile"))]
    lines += ["  - model: authentik_core.application", "    identifiers:", f"      slug: {yq(slug)}", "    attrs:",
              f"      name: {yq(c.name)}", "      provider: !KeyOf provider"]
    if c.root_url:
        lines.append(f"      meta_launch_url: {yq(c.root_url)}")
    for group in c.groups:
        lines += ["  - model: authentik_core.group", "    identifiers:", f"      name: {yq(group)}", "    attrs:",
                  f"      name: {yq(group)}"]
    return "\n".join(lines) + "\n"


def _authentik_script(provider: IdentityProvider, c: ClientSpec) -> str | None:
    target = compose_target(provider)
    if target is None:
        return None
    compose_dir, service = target
    slug = c.app_slug or c.client_id
    return ("#!/usr/bin/env bash\n"
            f"# Applies authentik-blueprint.yaml in the {service} container of {provider.name} (docker compose exec):\n"
            f"# creates or updates the {c.protocol.upper()} provider and application for {c.name}. Safe to run again.\n"
            "# Generated by the Atrium Patch Agent. Assumes the default blueprints folder /blueprints in the container.\n"
            + textwrap.dedent(f"""\
        set -euo pipefail
        export MSYS_NO_PATHCONV=1  # Git Bash on Windows: pass container paths through unchanged
        HERE="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
        COMPOSE_DIR="${{AUTHENTIK_COMPOSE_DIR:-{compose_dir}}}"
        SERVICE="${{AUTHENTIK_SERVICE:-{service}}}"
        FILE={sh(f"custom/atrium-{slug}.yaml")}
        cd "$COMPOSE_DIR"
        docker compose exec -T "$SERVICE" sh -c "mkdir -p /blueprints/custom && cat > /blueprints/$FILE" < "$HERE/authentik-blueprint.yaml"
        docker compose exec -T "$SERVICE" ak apply_blueprint "$FILE"
        echo "Applied the blueprint for {c.client_id}"
        """))


def _generic_instructions(provider: IdentityProvider, c: ClientSpec) -> str:
    lines = [f"# Register {c.name} at {provider.name}", "",
             f"Generated by the Atrium Patch Agent. {provider.name} ({KIND_LABEL[provider.kind]}) has no registration "
             "format the hub writes, so register the client by hand with these values:", ""]
    if c.protocol == "saml":
        lines += ["- Protocol: SAML 2.0", f"- Service provider entity ID: `{c.client_id}`",
                  f"- Assertion consumer service (POST): `{c.acs_url}`"]
        if c.slo_url:
            lines.append(f"- Single logout service: `{c.slo_url}`")
    else:
        lines += ["- Protocol: OpenID Connect, authorization code flow", f"- Client ID: `{c.client_id}`",
                  "- Client type: " + ("public, PKCE S256 (no secret)" if c.public else "confidential (client secret, sent with HTTP Basic)"),
                  "- Redirect URIs: " + ", ".join(f"`{u}`" for u in c.redirect_uris),
                  f"- Scopes: `{SCOPES}`"]
        if not c.public:
            lines.append(f"- Client secret: `{CLIENT_SECRET}`")
    lines += ["", "If the provider generates the client ID or secret itself (Zitadel does), replace the generated values "
              "in the other files of this folder with the ones it shows."]
    if provider.kind == "authelia" and c.protocol == "oidc":
        lines += ["", "For Authelia, add the client under `identity_providers.oidc.clients` in its configuration. Authelia "
                  "recommends storing a hash of the secret (`authelia crypto hash generate pbkdf2`) rather than the secret:", "",
                  "```yaml", f"- client_id: {yq(c.client_id)}", f"  client_name: {yq(c.name)}",
                  "  public: true" if c.public else "  client_secret: '<hash of the client secret above>'",
                  "  authorization_policy: two_factor", "  redirect_uris:", *[f"    - {yq(u)}" for u in c.redirect_uris],
                  "  scopes: [openid, profile, email, groups]", "```"]
    return "\n".join(lines) + "\n"


def registration(provider: IdentityProvider, c: ClientSpec, folder: str = "idp") -> Registration:
    """Files that register `c` at `provider`, written to `folder` (relative to where the patch lands; "" = there)."""
    files: list[FileChange] = []
    steps: list[str] = []
    script = None

    def at(name: str) -> str:
        return f"{folder}/{name}" if folder else name

    if not provider.configured:
        steps.append(f"Set the public URL of {provider.name} in Integration hub > Identity; the files use a placeholder until then.")
    if provider.kind == "keycloak":
        files.append(FileChange(path=at("keycloak-client.json"), content=json.dumps(keycloak_client(c), indent=2) + "\n"))
        host, compose = _keycloak_scripts(provider, c)
        files.append(FileChange(path=at("register-keycloak.sh"), content=host))
        if compose:
            script = at("register-keycloak-compose.sh")
            files.append(FileChange(path=script, content=compose))
            steps.append(f"Register the client at {provider.name}: run {script} (docker compose exec into {provider.name}); "
                         "the Register button has the Operator Agent run it.")
        else:
            script = at("register-keycloak.sh")
            steps.append(f"Register the client at {provider.name}: set KEYCLOAK_ADMIN_USER and KEYCLOAK_ADMIN_PASSWORD, then "
                         f"run {script}; the Register button has the Operator Agent run it.")
    elif provider.kind == "authentik":
        files.append(FileChange(path=at("authentik-blueprint.yaml"), content=authentik_blueprint(provider, c)))
        compose = _authentik_script(provider, c)
        if compose:
            script = at("register-authentik-compose.sh")
            files.append(FileChange(path=script, content=compose))
            steps.append(f"Register the client at {provider.name}: run {script} to apply the blueprint; the Register button "
                         "has the Operator Agent run it.")
        else:
            steps.append(f"Register the client at {provider.name}: copy {at('authentik-blueprint.yaml')} into authentik's "
                         "blueprints folder (/blueprints/custom in the container) or run `ak apply_blueprint` with it.")
    else:
        files.append(FileChange(path=at("REGISTER.md"), content=_generic_instructions(provider, c)))
        steps.append(f"Register the client at {provider.name} by hand: {at('REGISTER.md')} has the values.")
    if any(h in provider.base_url for h in ("//localhost", "//127.0.0.1")):
        steps.append(f"{provider.name} is addressed as localhost. Tools running in containers cannot reach it there: set its "
                     "public URL (Integration hub > Identity) to an address browsers and containers both reach.")
    return Registration(files=files, steps=steps, script=script)


