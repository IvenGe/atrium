def nextcloud(ctx: SsoContext) -> SsoConfig:
    ident = re.sub(r"[^A-Za-z0-9_-]+", "-", ctx.provider.name).strip("-") or "sso"
    script = "\n".join([
        "#!/usr/bin/env bash",
        f"# Connects {one_line(ctx.tool.name)} to {one_line(ctx.provider.name)} with the official user_oidc app. Generated by the Atrium Patch Agent.",
        "# Run it on the Nextcloud host (NEXTCLOUD_OCC=/var/www/nextcloud/occ, as the web server user), or for the",
        "# official container: NEXTCLOUD_CONTAINER=<container name> bash user-oidc.sh",
        "set -euo pipefail",
        "occ() {",
        '  if [ -n "${NEXTCLOUD_CONTAINER:-}" ]; then docker exec -u www-data "$NEXTCLOUD_CONTAINER" php occ "$@";',
        '  else php "${NEXTCLOUD_OCC:-occ}" "$@"; fi',
        "}",
        "occ app:install user_oidc || occ app:enable user_oidc",
        f"occ user_oidc:provider {sh(ident)} --clientid={sh(ctx.client_id)} --clientsecret={sh(CLIENT_SECRET)} \\",
        f"  --discoveryuri={sh(ctx.discovery)} >/dev/null",
        f'echo "Configured the {ident} provider in user_oidc"',
    ]) + "\n"
    # Assumption: user_oidc's callback is /apps/user_oidc/code (with /index.php/ when pretty URLs are off).
    return SsoConfig("oidc", [FileChange(path="sso/user-oidc.sh", content=script)],
                     [f"{ctx.url}/apps/user_oidc/code", f"{ctx.url}/index.php/apps/user_oidc/code"], [
                         "Run sso/user-oidc.sh once (it installs user_oidc and adds the provider). "
                         "Attribute mappings and group provisioning: `occ user_oidc:provider --help`."])


def _dashboards(wazuh: bool) -> Callable[[SsoContext], SsoConfig]:
    def generate(ctx: SsoContext) -> SsoConfig:
        security = "/etc/wazuh-indexer/opensearch-security" if wazuh else "/usr/share/opensearch/config/opensearch-security"
        tools = ("/usr/share/wazuh-indexer/plugins/opensearch-security/tools/securityadmin.sh" if wazuh
                 else "/usr/share/opensearch/plugins/opensearch-security/tools/securityadmin.sh")
        certs = "/etc/wazuh-indexer/certs" if wazuh else "/usr/share/opensearch/config"
        java = "/usr/share/wazuh-indexer/jdk" if wazuh else "/usr/share/opensearch/jdk"
        dashboards_yml = "/etc/wazuh-dashboard/opensearch_dashboards.yml" if wazuh else "config/opensearch_dashboards.yml"
        product = "Wazuh indexer" if wazuh else "OpenSearch"
        domain = "\n".join([
            f"# OpenID Connect for the {product} security plugin, generated by the Atrium Patch Agent.",
            f"# Merge this block into {security}/config.yml under config.dynamic.authc (keep basic_internal_auth_domain),",
            "# then push it with apply-security-config.sh.",
            "openid_auth_domain:",
            "  http_enabled: true",
            "  transport_enabled: true",
            "  order: 1",
            "  http_authenticator:",
            "    type: openid",
            "    challenge: false",
            "    config:",
            "      subject_key: preferred_username",
            "      roles_key: groups",
            f"      openid_connect_url: {json.dumps(ctx.discovery)}",
            "  authentication_backend:",
            "    type: noop",
        ]) + "\n"
        dashboards = "\n".join([
            f"# Add to {dashboards_yml} and restart the dashboard. Generated by the Atrium Patch Agent.",
            "# Keep this file private: it holds the client secret.",
            "opensearch_security.auth.multiple_auth_enabled: true",
            'opensearch_security.auth.type: ["basicauth", "openid"]',
            f"opensearch_security.openid.connect_url: {json.dumps(ctx.discovery)}",
            f"opensearch_security.openid.client_id: {json.dumps(ctx.client_id)}",
            f"opensearch_security.openid.client_secret: {json.dumps(CLIENT_SECRET)}",
            f"opensearch_security.openid.scope: {json.dumps(SCOPES)}",
            f"opensearch_security.openid.base_redirect_url: {json.dumps(ctx.url)}",
        ]) + "\n"
        # The securityadmin.sh call follows Wazuh's Keycloak SSO guide; older OpenSearch versions also need `-t config`.
        apply = "\n".join([
            "#!/usr/bin/env bash",
            f"# Pushes config.yml to the {product} security index. Run it on an indexer node as root after merging",
            "# opensearch-security-openid.yml into config.yml. Generated by the Atrium Patch Agent.",
            "set -euo pipefail",
            f'SECURITY_DIR="${{SECURITY_DIR:-{security}}}"',
            f'SECURITYADMIN="${{SECURITYADMIN:-{tools}}}"',
            f'CERTS_DIR="${{CERTS_DIR:-{certs}}}"',
            f'export JAVA_HOME="${{JAVA_HOME:-{java}}}"',
            'bash "$SECURITYADMIN" -f "$SECURITY_DIR/config.yml" -icl -key "$CERTS_DIR/admin-key.pem" \\',
            '  -cert "$CERTS_DIR/admin.pem" -cacert "$CERTS_DIR/root-ca.pem" -h "${INDEXER_HOST:-localhost}" -nhnv',
        ]) + "\n"
        return SsoConfig("oidc", [FileChange(path="sso/opensearch-security-openid.yml", content=domain),
                                  FileChange(path="sso/opensearch_dashboards.yml", content=dashboards),
                                  FileChange(path="sso/apply-security-config.sh", content=apply)],
                         [f"{ctx.url}/auth/openid/login"], [
                             f"Merge sso/opensearch-security-openid.yml into {security}/config.yml and run sso/apply-security-config.sh.",
                             "Map the backend role atrium-admins to all_access in roles_mapping.yml and apply it the same way.",
                             f"Add sso/opensearch_dashboards.yml to {dashboards_yml} and restart the dashboard.",
                             f"The {product} must trust the TLS certificate of {ctx.provider.name}."])
    return generate


