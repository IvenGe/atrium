"""How well-known tools do single sign-on natively, and the configuration that connects each to an identity provider.

Every generator returns the tool-side files (they land in the hub's adapter folder for the tool, ``sso/``), the
redirect URIs to register at the provider and the steps a person still has to do. Client secrets only appear as
the ``CLIENT_SECRET`` placeholder; the hub fills it in when it writes the adapter files.

Sources the generators follow (checked against the vendors' documentation, October 2026):
Grafana generic OAuth (GF_AUTH_GENERIC_OAUTH_*, callback /login/generic_oauth), Gitea/Forgejo CLI
(`admin auth add-oauth --provider openidConnect --auto-discover-url`, callback /user/oauth2/<name>/callback),
MinIO (MINIO_IDENTITY_OPENID_*, MINIO_BROWSER_REDIRECT_URL, callback /oauth_callback), BookStack (AUTH_METHOD=oidc,
OIDC_*, callback /oidc/callback), Outline (OIDC_*, callback /auth/oidc.callback), Nextcloud user_oidc
(`occ user_oidc:provider --clientid --clientsecret --discoveryuri`), Wazuh / OpenSearch Dashboards (security plugin
openid_auth_domain, opensearch_security.openid.*, securityadmin.sh, callback /auth/openid/login), CISO Assistant
(SSO settings in its UI, callback /api/accounts/oidc/openid_connect/login/callback/), Snipe-IT (SAML only: /saml/acs,
/saml/sls, entity ID = its URL), Zammad (OIDC in its UI, public client with PKCE, callback
/auth/openid_connect/callback). Where a detail could not be confirmed it is marked "assumption" below.
"""

