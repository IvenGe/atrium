def tool_url(m: Manifest) -> str:
    """The tool's base URL as people open it."""
    url = m.ui.url or m.api.base_url or (f"http://localhost:{m.launch.port}" if m.launch.port else "https://tool.example.com")
    return url.rstrip("/")


def client_id_for(tool: Tool) -> str:
    return f"hub-{tool.id}"


@dataclass
class SsoContext:
    tool: Tool
    provider: IdentityProvider
    protocol: Protocol
    url: str  # the tool's base URL
    client_id: str

    @property
    def issuer(self) -> str:
        return self.provider.client_issuer(self.client_id)

    @property
    def discovery(self) -> str:
        return self.provider.discovery_url(self.client_id)

    def endpoint(self, name: str) -> str:
        """A provider endpoint; for providers whose layout is unknown, a placeholder naming where to find it."""
        value = self.provider.endpoints(self.client_id).get(name)
        key = {"authorize": "authorization_endpoint", "token": "token_endpoint", "userinfo": "userinfo_endpoint",
               "end_session": "end_session_endpoint"}[name]
        return value or f"<{key} from {self.discovery}>"

    @property
    def endpoints_known(self) -> bool:
        return self.provider.kind != "generic"


@dataclass
class SsoConfig:
    protocol: Protocol
    files: list[FileChange]
    redirect_uris: list[str]
    steps: list[str] = field(default_factory=list)
    public_client: bool = False
    acs_url: str | None = None  # SAML
    slo_url: str | None = None
    entity_id: str | None = None  # SAML service provider entity id (the client id at the provider)


@dataclass(frozen=True)
class CatalogEntry:
    key: str
    name: str
    aliases: tuple[str, ...]  # matched against the tool's id, name and source
    protocols: tuple[Protocol, ...]  # natively supported in the free edition, preferred first; () = none
    redirect: str  # callback pattern, {url} = the tool's base URL
    generate: Callable[[SsoContext], SsoConfig] | None = None
    note: str = ""


def env_text(title: str, values: dict[str, str], comments: dict[str, str] | None = None) -> str:
    """KEY=value lines that docker compose env_file and dotenv parsers (Laravel, Node) read the same way."""
    lines = [f"# {one_line(title)}", "# Generated by the Atrium Patch Agent. Keep this file private: it holds the client secret."]
    for key, value in values.items():
        if comments and key in comments:
            lines.append(f"# {one_line(comments[key])}")
        needs_quotes = value == "" or re.search(r"[\s#'\"\\]", value)
        lines.append(f"{key}={json.dumps(value) if needs_quotes else value}")
    return "\n".join(lines) + "\n"


def _unknown_endpoints(ctx: SsoContext) -> list[str]:
    if ctx.endpoints_known:
        return []
    return [f"{ctx.provider.name} is a generic OpenID Connect provider: replace the <..._endpoint> placeholders with the "
            f"values from {ctx.discovery}."]


