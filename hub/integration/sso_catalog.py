# (pattern on the key without its OIDC_/OAUTH2_ prefix, what to fill in). First match wins.
ENV_FILL: tuple[tuple[str, str], ...] = (
    (r"CLIENT_?ID$", "client_id"),
    (r"CLIENT_?SECRET$|^SECRET$", "client_secret"),
    (r"(DISCOVERY|WELL_?KNOWN|CONFIG(URATION)?)_?(URL|URI|ENDPOINT)?$", "discovery"),
    (r"ISSUER(_?(URL|URI|BASE_URL))?$", "issuer"),
    (r"(REDIRECT|CALLBACK)_?(URL|URI)S?$", "redirect"),
    (r"(AUTHORI[SZ]ATION|AUTHORI[SZ]E|AUTH)_?(URL|URI|ENDPOINT)$", "authorize"),
    (r"TOKEN_?(URL|URI|ENDPOINT)$", "token"),
    (r"USER_?INFO_?(URL|URI|ENDPOINT)$|PROFILE_?(URL|URI)$", "userinfo"),
    (r"(LOGOUT|END_?SESSION)_?(URL|URI|ENDPOINT)$", "end_session"),
    (r"SCOPES?$", "scopes"),
    (r"^ENABLED?$", "enabled"),
    (r"^(DISPLAY_?NAME|PROVIDER_?NAME|BUTTON_?(TEXT|LABEL)|LABEL|NAME)$", "name"),
)


def env_example(tool: Tool) -> dict[str, str]:
    """Key -> value of the tool's .env example (empty when it has none on disk)."""
    if not tool.path:
        return {}
    values: dict[str, str] = {}
    for name in ENV_FILES:
        text = read_repo_file(Path(tool.path), name, 200_000)  # never through a symbolic link out of the repository
        if text is not None:
            values.update(parse_env_file(text))
    return values


def env_fill(ctx: SsoContext, keys: list[str], example: dict[str, str]) -> tuple[dict[str, str], list[str], str | None]:
    """Values for exactly `keys`, the keys left as in the example, and the callback path the example shows."""
    filled: dict[str, str] = {}
    unfilled: list[str] = []
    callback = None
    for key in keys:
        bare = re.sub(r"^(OIDC|OPENID|OAUTH2?)_", "", key.upper())
        what = next((w for pattern, w in ENV_FILL if re.search(pattern, bare)), None)
        old = example.get(key, "")
        if what == "redirect":
            path = re.sub(r"^[a-z]+://[^/]+", "", old) if old else ""
            callback = path if path.startswith("/") else callback
            filled[key] = f"{ctx.url}{path}" if path.startswith("/") else f"{ctx.url}/<callback path>"
        elif what in ("authorize", "token", "userinfo", "end_session"):
            filled[key] = ctx.endpoint(what)
        elif what == "scopes":
            filled[key] = SCOPES.replace(" ", ",") if "," in old else SCOPES
        elif what is not None:
            filled[key] = {"client_id": ctx.client_id, "client_secret": CLIENT_SECRET, "discovery": ctx.discovery,
                           "issuer": ctx.issuer, "enabled": "true", "name": ctx.provider.name}[what]
        else:
            filled[key] = old
            unfilled.append(key)
    return filled, unfilled, callback


def generic_env(ctx: SsoContext) -> SsoConfig:
    """Fill exactly the OIDC_* / OAUTH2_* keys the tool's .env example exposes."""
    keys = ctx.tool.manifest.auth.env_keys if ctx.tool.manifest else []
    values, unfilled, callback = env_fill(ctx, keys, env_example(ctx.tool))
    comments = {k: "Not filled by the hub (kept from the example): check it." for k in unfilled}
    steps = [f"Merge sso/oidc.env into {ctx.tool.name}'s environment and restart it."]
    if callback:
        redirect = [f"{ctx.url}{callback}"]
    else:
        redirect = [f"{ctx.url}/*"]
        steps.append(f"The callback path of {ctx.tool.name} is unknown, so any path under {ctx.url}/ is allowed at "
                     f"{ctx.provider.name}. Look it up in the tool's documentation and narrow the redirect URI.")
    if unfilled:
        steps.append("Check the keys the hub could not fill: " + ", ".join(unfilled) + ".")
    return SsoConfig("oidc", [FileChange(path="sso/oidc.env", content=env_text(
        f"{ctx.tool.name} signs in through {ctx.provider.name}: the OIDC keys from its .env example", values, comments))],
        redirect, [*steps, *_unknown_endpoints(ctx)])


def generic_oidc(ctx: SsoContext) -> SsoConfig:
    """A tool that supports OpenID Connect in a way the hub does not know: the values to enter in its settings."""
    values = {"OIDC_ISSUER": ctx.issuer, "OIDC_DISCOVERY_URL": ctx.discovery, "OIDC_CLIENT_ID": ctx.client_id,
              "OIDC_CLIENT_SECRET": CLIENT_SECRET, "OIDC_SCOPES": SCOPES}
    return SsoConfig("oidc", [FileChange(path="sso/oidc-values.env", content=env_text(
        f"Values for {ctx.tool.name}'s OpenID Connect settings ({ctx.provider.name})", values))], [f"{ctx.url}/*"], [
            f"Enter the values from sso/oidc-values.env in {ctx.tool.name}'s single sign-on settings.",
            f"The callback path of {ctx.tool.name} is unknown, so any path under {ctx.url}/ is allowed at "
            f"{ctx.provider.name}. Look it up in the tool's documentation and narrow the redirect URI."])


def native(tool: Tool, provider: IdentityProvider, extra: tuple[CatalogEntry, ...] = ()) -> tuple[str, Protocol] | None:
    """(how, protocol) when `tool` can sign in through `provider` natively; how is a catalog key, "env" or "generic".
    `extra`: recipes from extension packs."""
    m = tool.manifest
    if m is None or "oauth2-proxy" in (m.auth.notes or ""):
        return None
    entry = match(tool, extra)
    if entry is not None:
        protocol = next((p for p in entry.protocols if p in provider.protocols), None)
        return (entry.key, protocol) if protocol else None
    if "oidc" not in provider.protocols:
        return None
    if m.auth.env_keys:
        return "env", "oidc"
    if m.auth.sso in ("oidc", "oauth2"):
        return "generic", "oidc"
    return None


def generate(tool: Tool, provider: IdentityProvider, extra: tuple[CatalogEntry, ...] = ()) -> SsoConfig | None:
    """The tool-side configuration that connects `tool` to `provider`, or None if it cannot sign in natively."""
    how = native(tool, provider, extra)
    if how is None or tool.manifest is None:
        return None
    key, protocol = how
    ctx = SsoContext(tool=tool, provider=provider, protocol=protocol, url=tool_url(tool.manifest), client_id=client_id_for(tool))
    if key == "env":
        return generic_env(ctx)
    if key == "generic":
        return generic_oidc(ctx)
    entry = next(e for e in (*CATALOG, *extra) if e.key == key)
    assert entry.generate is not None
    return entry.generate(ctx)
