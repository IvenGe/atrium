def _gitea(binary: str) -> Callable[[SsoContext], SsoConfig]:
    def generate(ctx: SsoContext) -> SsoConfig:
        source = re.sub(r"[^a-z0-9-]+", "-", ctx.provider.name.lower()).strip("-") or "sso"
        redirect = f"{ctx.url}/user/oauth2/{source}/callback"
        script = "\n".join([
            "#!/usr/bin/env bash",
            f"# Adds {one_line(ctx.provider.name)} as an OpenID Connect sign-in source of {one_line(ctx.tool.name)}. Generated by the Atrium Patch Agent.",
            f"# Run it where {binary} and its app.ini live, as the user {binary} runs as - or for a container:",
            f"#   {binary.upper()}_CONTAINER=<container name> bash add-oauth-source.sh   (runs docker exec -u git)",
            f"# The source name \"{source}\" is part of the callback URL; if it already exists, use `{binary} admin auth update-oauth`.",
            "set -euo pipefail",
            f"ARGS=(admin auth add-oauth --name {sh(source)} --provider openidConnect --key {sh(ctx.client_id)}",
            f"      --secret {sh(CLIENT_SECRET)} --auto-discover-url {sh(ctx.discovery)})",
            f'if [ -n "${{{binary.upper()}_CONTAINER:-}}" ]; then',
            f'  docker exec -u git "${{{binary.upper()}_CONTAINER}}" {binary} "${{ARGS[@]}}"',
            "else",
            f'  {binary} "${{ARGS[@]}}"',
            "fi",
            f'echo "Added the {source} sign-in source"',
        ]) + "\n"
        return SsoConfig("oidc", [FileChange(path="sso/add-oauth-source.sh", content=script)], [redirect], [
            f"Run sso/add-oauth-source.sh once on the {ctx.tool.name} host (or with {binary.upper()}_CONTAINER set), "
            f"then sign in with \"Sign in with {source}\". ROOT_URL in app.ini must be {ctx.url}/."])
    return generate


