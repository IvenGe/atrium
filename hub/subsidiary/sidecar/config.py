"""The sidecar's configuration and its state directory.

config.json is generated by Atrium with the sidecar bundle (templates/sidecar/config.json) and holds no secret: where
Atrium and the bridge are, the subsidiary's and the tool's ids, and optionally a CA file and a pin of Atrium's TLS
certificate. The state directory (0700) holds what the sidecar owns: its Ed25519 private key and its token (0600 files,
written atomically), the claimed-audit spool, the inbox and events cursors and the grants in flight. The one-time
enrollment code comes from the environment (ATRIUM_ENROLLMENT_CODE) on the first start only and is never written.
"""

from __future__ import annotations

import ipaddress
import json
import os
import re
import stat
from pathlib import Path
from typing import Any, Literal, Mapping
from urllib.parse import urlsplit

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from pydantic import BaseModel, ConfigDict, Field, ValidationError

from .. import contract

ALLOW_HTTP_ENV = "HUB_SUBSIDIARY_ALLOW_HTTP"
ENROLL_ENV = "ATRIUM_ENROLLMENT_CODE"
DEFAULT_STATE_DIR = "/var/lib/atrium-sidecar"
KEY_FILE, TOKEN_FILE = "key", "token.json"
PIN_RE = re.compile(r"^[0-9a-f]{64}$")


class ConfigError(ValueError):
    """config.json is missing, unreadable or unsafe: the sidecar does not start (exit code 1)."""


class SidecarConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    atrium_url: str = Field(max_length=500)
    subsidiary_id: str
    tool_id: str
    mode: Literal["bridge", "sidecar_only"]
    bridge_url: str | None = Field(None, max_length=500)
    ca_file: str | None = Field(None, max_length=500)
    atrium_cert_sha256: str | None = None
    state_dir: str = Field(DEFAULT_STATE_DIR, max_length=500)

    @property
    def api(self) -> str:
        """The sidecar API's base URL."""
        return self.atrium_url.rstrip("/") + "/api/subsidiary/v1/"

    @property
    def atrium_host(self) -> str:
        return urlsplit(self.atrium_url).hostname or ""


def loopback(host: str) -> bool:
    if host == "localhost":
        return True
    try:
        return ipaddress.ip_address(host.strip("[]")).is_loopback
    except ValueError:
        return False


def _url_problem(name: str, value: str) -> str | None:
    parts = urlsplit(value)
    if parts.scheme not in ("http", "https") or not parts.hostname:
        return f"{name} is an http(s) URL"
    if parts.username or parts.password or parts.query or parts.fragment:
        return f"{name} carries no credentials, query or fragment"
    return None


def check(config: SidecarConfig, env: Mapping[str, str]) -> list[str]:
    """What is wrong with a parsed config, for the environment it runs in (6.4: plain http to Atrium only to a
    loopback address, or with HUB_SUBSIDIARY_ALLOW_HTTP=1)."""
    problems = [p for p in (_url_problem("atrium_url", config.atrium_url),
                            _url_problem("bridge_url", config.bridge_url) if config.bridge_url else None) if p]
    parts = urlsplit(config.atrium_url)
    if not problems and parts.scheme == "http" and not loopback(parts.hostname or "") \
            and env.get(ALLOW_HTTP_ENV) != "1":
        problems.append(f"atrium_url must use https (plain http only to a loopback address, or with "
                        f"{ALLOW_HTTP_ENV}=1)")
    if not contract.SUBSIDIARY_ID_RE.match(config.subsidiary_id):
        problems.append("subsidiary_id is sub_ and 12 hex digits")
    if not contract.TOOL_ID_RE.match(config.tool_id):
        problems.append("tool_id is not a tool id")
    if config.mode == "bridge" and not config.bridge_url:
        problems.append("bridge mode needs bridge_url: the tool's address, where its bridge is mounted")
    if config.atrium_cert_sha256 is not None and not PIN_RE.match(config.atrium_cert_sha256):
        problems.append("atrium_cert_sha256 is the SHA-256 of Atrium's certificate (DER), 64 lowercase hex digits")
    if config.ca_file is not None and not Path(config.ca_file).is_file():
        problems.append("ca_file does not exist")
    return problems


def parse(data: Any, env: Mapping[str, str] | None = None) -> SidecarConfig:
    env = os.environ if env is None else env
    try:
        config = SidecarConfig.model_validate(data)
    except ValidationError as exc:
        where = ", ".join(".".join(str(p) for p in e.get("loc", ())) or "config" for e in exc.errors()[:5])
        raise ConfigError(f"config.json is not valid ({where})") from None
    problems = check(config, env)
    if problems:
        raise ConfigError("; ".join(problems))
    return config


def load(path: str | Path, env: Mapping[str, str] | None = None) -> SidecarConfig:
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ConfigError(f"cannot read {path}: {exc.__class__.__name__}") from None
    return parse(data, env)


