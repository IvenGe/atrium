class TokenFile(BaseModel):
    token: str
    subsidiary_id: str
    tool_id: str
    issued_at: float  # the sidecar's clock when it got the token (rotation at half-life)
    expires_at: float | None = None

    def due(self, now: float) -> bool:
        """Half its life is over: time to rotate."""
        return self.expires_at is not None and now >= self.issued_at + (self.expires_at - self.issued_at) / 2


class State:
    """The sidecar's own files. Secret files (the key, the token, the grants in flight) are 0600 and replaced
    atomically; the directory is 0700."""

    def __init__(self, root: str | Path):
        self.root = Path(root)

    def ensure(self) -> None:
        self.root.mkdir(mode=0o700, parents=True, exist_ok=True)
        if stat.S_IMODE(self.root.stat().st_mode) & 0o077:
            os.chmod(self.root, 0o700)

    def path(self, name: str) -> Path:
        return self.root / name

    def write(self, name: str, data: bytes) -> None:
        """Replace a file atomically, readable by this user only."""
        self.ensure()
        target, tmp = self.path(name), self.path(f".{name}.tmp")
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        try:
            os.write(fd, data)
            os.fsync(fd)
        finally:
            os.close(fd)
        os.chmod(tmp, 0o600)
        os.replace(tmp, target)

    def read(self, name: str) -> bytes | None:
        try:
            return self.path(name).read_bytes()
        except FileNotFoundError:
            return None

    def read_json(self, name: str) -> Any:
        raw = self.read(name)
        if raw is None:
            return None
        try:
            return json.loads(raw.decode("utf-8"))
        except (ValueError, UnicodeError):
            return None

    def write_json(self, name: str, data: Any) -> None:
        self.write(name, json.dumps(data, separators=(",", ":"), sort_keys=True).encode())

    def key(self) -> Ed25519PrivateKey | None:
        raw = self.read(KEY_FILE)
        if raw is None:
            return None
        try:
            return contract.private_key(raw.decode("ascii").strip())
        except (ValueError, UnicodeError):
            raise ConfigError(f"{self.path(KEY_FILE)} is not an Ed25519 private key") from None

    def remove(self, name: str) -> None:
        self.path(name).unlink(missing_ok=True)

    def new_key(self, *, replace: bool = False) -> Ed25519PrivateKey:
        """Generate the sidecar's own key: on the first start, and again only when it enrolls anew (a new one-time
        code after its token was refused)."""
        if self.read(KEY_FILE) is not None and not replace:
            raise ConfigError("the state directory already holds a key")
        key = contract.new_key()
        self.write(KEY_FILE, (contract.private_b64(key) + "\n").encode("ascii"))
        return key

    def token(self) -> TokenFile | None:
        data = self.read_json(TOKEN_FILE)
        try:
            return TokenFile.model_validate(data) if data is not None else None
        except ValidationError:
            raise ConfigError(f"{self.path(TOKEN_FILE)} is not a sidecar token file") from None

    def save_token(self, token: TokenFile) -> None:
        self.write(TOKEN_FILE, token.model_dump_json().encode())

    def loose(self) -> list[str]:
        """Secret files others can read (a warning: they were copied or changed outside the sidecar)."""
        found = []
        for name in (KEY_FILE, TOKEN_FILE):
            path = self.path(name)
            if path.exists() and stat.S_IMODE(path.stat().st_mode) & 0o077:
                found.append(name)
        return found
